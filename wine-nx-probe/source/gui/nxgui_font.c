#define NXGUI_FONT_GLYPH_COUNT (sizeof(nxgui_font_table) / sizeof(nxgui_font_table[0]))

static const nxgui_glyph_t *nxgui_font_lookup( char c )
{
    size_t i;
    if (c >= 'a' && c <= 'z') c -= ('a' - 'A');
    for (i = 0; i < NXGUI_FONT_GLYPH_COUNT; i++)
        if (nxgui_font_table[i].c == c) return &nxgui_font_table[i];
    return NULL;   /* unmapped char -- caller renders it as a blank cell */
}

int nxgui_font_glyph_row( char c, int row )
{
    const nxgui_glyph_t *g = nxgui_font_lookup( c );
    if (!g || row < 0 || row > 6) return 0;
    return g->rows[row];
}
