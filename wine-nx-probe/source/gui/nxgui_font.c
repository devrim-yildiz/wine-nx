/* Embedded 5x7 bitmap font -- classic dot-matrix proportions (same family
 * as HD44780 character LCDs and countless embedded UIs), chosen over a
 * TTF/stb_truetype approach specifically because it needs zero font
 * files staged on the SD card and zero rasterizer beyond "read 7 rows of
 * 5 bits and blit filled squares" -- this whole file plus nxgui_draw_text()
 * in nxgui.c is the entire text stack.
 *
 * UPPERCASE ONLY, no lowercase glyphs: nxgui_draw_text() upper-cases
 * every character before lookup. This is a deliberate scope cut, not an
 * oversight -- hand-authoring a full-fidelity 5x7 lowercase set (with
 * proper descenders needing an 8th/9th row) roughly doubles this file's
 * size and its error surface for a purely cosmetic gain; rendering
 * everything (menu labels, game titles, file paths) in caps is also a
 * legitimate, common "clean/modern" console-UI style choice in its own
 * right (not just a workaround), matching how several real console
 * launchers already lean on all-caps or title-case chrome. Extend this
 * table with a lowercase block later if a specific screen genuinely
 * needs mixed case -- nothing else in nxgui.c assumes uppercase-only,
 * only this file's own glyph table does.
 *
 * NOT YET HARDWARE-VALIDATED -- in particular, nobody has visually
 * confirmed every glyph below actually looks like its letter on a real
 * screen yet. Wrong bits here render as a wrong-looking (not crashing,
 * not misbehaving) character -- a cosmetic bug, safe to ship and fix
 * incrementally once actually seen rendered.
 */
